const { MR_IID, PROJECT_ID, mockApi } = vi.hoisted(() => {
  const PROJECT_ID = '42'
  const MR_IID = 12
  // `src/env.ts` and `src/context.ts` capture CI variables at module load.
  process.env.CI_PROJECT_ID = PROJECT_ID
  process.env.CI_MERGE_REQUEST_IID = String(MR_IID)
  process.env.CI_MERGE_REQUEST_PROJECT_URL =
    'https://gitlab.example/group/project'
  process.env.CI_MERGE_REQUEST_SOURCE_BRANCH_NAME = 'feature'
  process.env.CI_MERGE_REQUEST_SOURCE_BRANCH_SHA = 'abc123'
  process.env.CI_MERGE_REQUEST_TITLE = 'Add feature'
  process.env.GITLAB_CI_USER_NAME = 'ci-bot'
  process.env.GITLAB_TOKEN = 'glpat-token'
  process.env.GITLAB_COMMENT_TYPE = 'discussion'
  process.env.GITLAB_COMMENT_DISCUSSION_AUTO_RESOLVE = '1'
  return {
    MR_IID,
    PROJECT_ID,
    mockApi: {
      MergeRequests: {
        allDiffs: vi.fn(),
      },
      MergeRequestDiscussions: {
        all: vi.fn(),
        create: vi.fn(),
        editNote: vi.fn(),
        resolve: vi.fn(),
      },
      MergeRequestNotes: {
        all: vi.fn(),
        create: vi.fn(),
        edit: vi.fn(),
      },
    },
  }
})

vi.mock('../src/api.ts', () => ({
  createApi: () => mockApi,
}))

vi.mock('../src/get-changed-packages.js', () => ({
  getChangedPackages: () =>
    Promise.resolve({
      changedPackages: ['pkg'],
      releasePlan: {
        changesets: [],
        releases: [],
      },
    }),
}))

const { comment } = await import('../src/comment.js')

const DISCUSSION_ID = 'disc-new'
const EXISTING_DISCUSSION_ID = 'disc-existing'

const changesetDiff = {
  new_file: true,
  new_path: '.changeset/brave-lions-sing.md',
}

const existingDiscussion = {
  id: EXISTING_DISCUSSION_ID,
  individual_note: false,
  notes: [
    {
      id: 11,
      author: { username: 'ci-bot' },
      body: 'previous\n__Generated By Changesets GitLab Bot__',
    },
  ],
}

const originalEnv = { ...process.env }

beforeEach(() => {
  vi.clearAllMocks()

  mockApi.MergeRequests.allDiffs.mockResolvedValue([])
  mockApi.MergeRequestDiscussions.all.mockResolvedValue([])
  mockApi.MergeRequestDiscussions.create.mockResolvedValue({
    id: DISCUSSION_ID,
  })
  mockApi.MergeRequestDiscussions.editNote.mockResolvedValue({
    id: existingDiscussion.notes[0].id,
  })
  mockApi.MergeRequestDiscussions.resolve.mockResolvedValue({
    id: DISCUSSION_ID,
  })
  mockApi.MergeRequestNotes.all.mockResolvedValue([])
  mockApi.MergeRequestNotes.create.mockResolvedValue({ id: 99 })
  mockApi.MergeRequestNotes.edit.mockResolvedValue({ id: 99 })
})

afterAll(() => {
  process.env = { ...originalEnv }
})

describe('comment', () => {
  test('creates the discussion and resolves it when a changeset is already present', async () => {
    mockApi.MergeRequests.allDiffs.mockResolvedValue([changesetDiff])

    await comment()

    expect(mockApi.MergeRequestDiscussions.create).toHaveBeenCalledOnce()
    expect(mockApi.MergeRequestDiscussions.create).toHaveBeenCalledWith(
      PROJECT_ID,
      MR_IID,
      expect.stringContaining('Changeset detected'),
    )
    expect(mockApi.MergeRequestDiscussions.resolve).toHaveBeenCalledWith(
      PROJECT_ID,
      MR_IID,
      DISCUSSION_ID,
      true,
    )
    expect(mockApi.MergeRequestDiscussions.create).toHaveBeenCalledBefore(
      mockApi.MergeRequestDiscussions.resolve,
    )
  })

  test('creates an open discussion when the merge request has no changeset', async () => {
    await comment()

    expect(mockApi.MergeRequestDiscussions.create).toHaveBeenCalledWith(
      PROJECT_ID,
      MR_IID,
      expect.stringContaining('No Changeset found'),
    )
    expect(mockApi.MergeRequestDiscussions.resolve).not.toHaveBeenCalled()
  })

  test('resolves an existing discussion when a changeset is present', async () => {
    mockApi.MergeRequests.allDiffs.mockResolvedValue([changesetDiff])
    mockApi.MergeRequestDiscussions.all.mockResolvedValue([existingDiscussion])

    await comment()

    expect(mockApi.MergeRequestDiscussions.create).not.toHaveBeenCalled()
    expect(mockApi.MergeRequestDiscussions.resolve).toHaveBeenCalledWith(
      PROJECT_ID,
      MR_IID,
      EXISTING_DISCUSSION_ID,
      true,
    )
    expect(mockApi.MergeRequestDiscussions.resolve).toHaveBeenCalledBefore(
      mockApi.MergeRequestDiscussions.editNote,
    )
  })

  test('reopens an existing discussion when the changeset is removed', async () => {
    mockApi.MergeRequestDiscussions.all.mockResolvedValue([existingDiscussion])

    await comment()

    expect(mockApi.MergeRequestDiscussions.resolve).toHaveBeenCalledWith(
      PROJECT_ID,
      MR_IID,
      EXISTING_DISCUSSION_ID,
      false,
    )
    const editCall = mockApi.MergeRequestDiscussions.editNote.mock.calls[0]
    expect(editCall[0]).toBe(PROJECT_ID)
    expect(editCall[1]).toBe(MR_IID)
    expect(editCall[2]).toBe(EXISTING_DISCUSSION_ID)
    expect(editCall[3]).toBe(existingDiscussion.notes[0].id)
    expect(JSON.stringify(editCall[4])).toContain('No Changeset found')
  })

  test('updates an individual note without reopening it when no changeset exists', async () => {
    mockApi.MergeRequestDiscussions.all.mockResolvedValue([
      { ...existingDiscussion, individual_note: true },
    ])

    await comment()

    expect(mockApi.MergeRequestDiscussions.resolve).not.toHaveBeenCalled()
    expect(mockApi.MergeRequestDiscussions.editNote).toHaveBeenCalledOnce()
  })

  test('does not resolve a new discussion when auto-resolve is disabled', async () => {
    process.env.GITLAB_COMMENT_DISCUSSION_AUTO_RESOLVE = 'false'
    vi.resetModules()
    const { comment: commentWithoutAutoResolve } =
      await import('../src/comment.js')
    mockApi.MergeRequests.allDiffs.mockResolvedValue([changesetDiff])

    await commentWithoutAutoResolve()

    expect(mockApi.MergeRequestDiscussions.create).toHaveBeenCalledOnce()
    expect(mockApi.MergeRequestDiscussions.resolve).not.toHaveBeenCalled()
  })

  test('does not reopen an existing discussion when auto-resolve is disabled', async () => {
    process.env.GITLAB_COMMENT_DISCUSSION_AUTO_RESOLVE = 'false'
    vi.resetModules()
    const { comment: commentWithoutAutoResolve } =
      await import('../src/comment.js')
    mockApi.MergeRequestDiscussions.all.mockResolvedValue([existingDiscussion])

    await commentWithoutAutoResolve()

    expect(mockApi.MergeRequestDiscussions.editNote).toHaveBeenCalledOnce()
    expect(mockApi.MergeRequestDiscussions.resolve).not.toHaveBeenCalled()
  })

  test('posts a note instead of a discussion when the comment type is note', async () => {
    process.env.GITLAB_COMMENT_TYPE = 'note'
    vi.resetModules()
    const { comment: commentAsNote } = await import('../src/comment.js')
    mockApi.MergeRequests.allDiffs.mockResolvedValue([changesetDiff])

    await commentAsNote()

    expect(mockApi.MergeRequestNotes.create).toHaveBeenCalledOnce()
    expect(mockApi.MergeRequestDiscussions.create).not.toHaveBeenCalled()
    expect(mockApi.MergeRequestDiscussions.resolve).not.toHaveBeenCalled()
  })
})
